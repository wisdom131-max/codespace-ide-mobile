package com.codespace.ide.chat.capabilities

/**
 * G-E-a MODEL CAPABILITY FLAGS (advisor GO 2026-10-20, phase G-E-a ONLY).
 *
 * Every capability is a NULLABLE Boolean: null means UNKNOWN and UNKNOWN is
 * NEVER treated as supported — the gate falls back to the provider constant
 * (today's behavior) whenever the whole chain yields null.
 *
 * Sources in priority order, first non-null wins PER FIELD:
 *   1. user override (per endpoint+model, plain wording, no secrets)
 *   2. live provider metadata (G-C refetch; OPENROUTER-STYLE only — parsed
 *      bounded, stored, NEVER trusted to drive code paths beyond these flags)
 *   3. bundled curated table (capability-table.json, generated by
 *      tools/gen_capability_table.py from LiteLLM's MIT catalog)
 *   4. provider constant (the existing ChatProvider.supportsImages seam)
 *
 * SCOPE OF EFFECT in G-E-a: images and PDF page images only — the flags for
 * audio/video are DECLARED but NOT USED until U5; supportsTools and
 * supportsStreaming are STORED but NEVER wired: a model claiming tool support
 * must never enable tool execution by itself (advisor condition d).
 */
data class ModelCapabilityFlags(
    val acceptsImages: Boolean? = null,
    /** U5 (media parts): declared now so U5 does not re-shape the table. NOT used in G-E-a. */
    val acceptsAudio: Boolean? = null,
    /** U5: declared, NOT used in G-E-a. */
    val acceptsVideo: Boolean? = null,
    /** Native PDF file input at the provider — NOT our extraction pipeline. */
    val acceptsPdf: Boolean? = null,
    /** Stored only. NEVER enables tool execution (advisor condition d). */
    val supportsTools: Boolean? = null,
    /** Max INPUT tokens when known; null = UNKNOWN. */
    val maxContextTokens: Long? = null,
    /** Stored only — no streaming decision reads it in G-E-a. */
    val supportsStreaming: Boolean? = null,
)

/**
 * The master switch. OFF BY DEFAULT (advisor condition a): with it off the
 * chat send path is BYTE-IDENTICAL to today — the gate returns the provider
 * constant unchanged and nothing else in the app reads the table. Do NOT
 * flip it on without the owner's word after the device pass.
 */
object ChatCapabilityFlags {
    @Volatile
    var capabilityTableEnabled: Boolean = false
}
